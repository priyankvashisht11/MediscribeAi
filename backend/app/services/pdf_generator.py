"""
pdf_generator.py — fpdf2 A4 clinical note PDF
"""

from datetime import datetime, timezone, timedelta

from fpdf import FPDF

IST = timedelta(hours=5, minutes=30)

PRIMARY = (1, 105, 111)   # #01696f
LIGHT_BG = (245, 248, 248)
DARK_TEXT = (31, 41, 55)
MUTED = (107, 114, 128)
BORDER = (209, 213, 219)


def _format_duration(started_at, ended_at) -> str:
    if not started_at or not ended_at:
        return "-"
    try:
        delta = ended_at - started_at
        seconds = int(delta.total_seconds())
        m, s = divmod(seconds, 60)
        return f"{m}m {s:02d}s"
    except Exception:
        return "-"


def _format_ist(dt: datetime | None) -> str:
    if not dt:
        return "-"
    try:
        ist_dt = dt.astimezone(timezone(IST))
        return ist_dt.strftime("%d %b %Y, %I:%M %p IST")
    except Exception:
        return str(dt)


_UNICODE_REPLACEMENTS = str.maketrans({
    "—": "-", "–": "-", "•": "-",  # em-dash, en-dash, bullet
    "‘": "'", "’": "'", "“": '"', "”": '"',  # curly quotes
    "…": "...",  # ellipsis
    "·": ".", "→": "->", "←": "<-",
})


def _ascii(text: str) -> str:
    """Strip non-Latin-1 characters that Helvetica can't render."""
    return text.translate(_UNICODE_REPLACEMENTS).encode("latin-1", errors="replace").decode("latin-1")


def _safe(value, fallback="-") -> str:
    if value is None or str(value).strip() == "":
        return fallback
    return _ascii(str(value).strip())


class NotePDF(FPDF):
    def __init__(self, doctor_name: str, patient_name: str, session_date: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.doctor_name = doctor_name
        self.patient_name = patient_name
        self.session_date = session_date
        self.set_margins(18, 18, 18)
        self.set_auto_page_break(auto=True, margin=18)

    def header(self):
        # Teal top bar
        self.set_fill_color(*PRIMARY)
        self.rect(0, 0, 210, 12, "F")
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 11)
        self.set_xy(18, 2.5)
        self.cell(80, 7, "Chartr", ln=0)
        self.set_font("Helvetica", "", 8)
        self.set_x(100)
        self.cell(92, 7, f"Clinical Note  |  {self.session_date}", align="R", ln=0)
        self.set_text_color(*DARK_TEXT)
        self.ln(16)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*MUTED)
        self.cell(0, 5, f"Generated by Chartr  |  Confidential  |  Page {self.page_no()}", align="C")

    def section_title(self, title: str):
        self.set_fill_color(*PRIMARY)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 9)
        self.cell(0, 7, f"  {title}", ln=1, fill=True)
        self.set_text_color(*DARK_TEXT)
        self.ln(2)

    def body_text(self, text: str):
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*DARK_TEXT)
        self.multi_cell(0, 5, text, ln=1)
        self.ln(2)

    def kv_row(self, label: str, value: str):
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(*MUTED)
        self.cell(50, 5, label.upper(), ln=0)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*DARK_TEXT)
        self.multi_cell(0, 5, value, ln=1)


def generate_note_pdf(
    note: dict,
    session: dict,
    doctor_name: str,
    patient_name: str = "Unknown",
    patient_age: int | None = None,
    patient_gender: str | None = None,
) -> bytes:
    # Strip leading "Dr." / "Dr " so we can add it consistently ourselves
    _bare = doctor_name.strip()
    for prefix in ("Dr. ", "Dr.","DR. ", "DR."):
        if _bare.startswith(prefix):
            _bare = _bare[len(prefix):].strip()
            break
    doctor_name = _bare

    session_date = _format_ist(session.get("started_at") or session.get("created_at"))
    duration = _format_duration(session.get("started_at"), session.get("ended_at"))
    confidence_pct = round((note.get("confidence_score") or 0) * 100)
    is_finalized = note.get("is_finalized", False)
    finalized_at = _format_ist(note.get("finalized_at")) if is_finalized else None

    icd_codes = note.get("icd_codes") or []
    icd_text = ", ".join(
        f"{c['code']} – {c.get('description','')}" for c in icd_codes if isinstance(c, dict)
    ) or "None suggested"
    icd_text = _ascii(icd_text)

    pdf = NotePDF(doctor_name=doctor_name, patient_name=patient_name, session_date=session_date)
    pdf.add_page()

    # ── Patient / Session info block ───────────────────────────────────────────
    pdf.set_fill_color(*LIGHT_BG)
    y_start = pdf.get_y()
    pdf.rect(18, y_start, 174, 28, "F")

    pdf.set_xy(22, y_start + 3)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(*DARK_TEXT)
    pdf.cell(0, 7, patient_name, ln=1)

    pdf.set_x(22)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(*MUTED)
    age_gender = " / ".join(filter(None, [
        f"{patient_age}y" if patient_age else None,
        patient_gender,
    ]))
    info_line = "  |  ".join(filter(None, [
        age_gender or None,
        f"Dr. {doctor_name}",
        f"Duration: {duration}",
        f"Confidence: {confidence_pct}%",
        "Finalized" if is_finalized else None,
    ]))
    pdf.cell(0, 5, info_line, ln=1)
    pdf.set_text_color(*DARK_TEXT)
    pdf.set_y(y_start + 31)

    # ── Chief Complaint ────────────────────────────────────────────────────────
    cc = _safe(note.get("chief_complaint"), "Not documented")
    pdf.section_title("CHIEF COMPLAINT")
    pdf.body_text(cc)

    # ── SOAP ──────────────────────────────────────────────────────────────────
    pdf.section_title("SUBJECTIVE (S)")
    pdf.body_text(_safe(note.get("subjective"), "Not documented"))

    hpi = _safe(note.get("history_of_present_illness"), "")
    if hpi and hpi != "—":
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 4, "History of Present Illness", ln=1)
        pdf.set_text_color(*DARK_TEXT)
        pdf.body_text(hpi)

    pdf.section_title("OBJECTIVE (O)")
    pdf.body_text(_safe(note.get("objective"), "Not documented"))

    exam = _safe(note.get("physical_examination"), "")
    if exam and exam != "—":
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 4, "Physical Examination", ln=1)
        pdf.set_text_color(*DARK_TEXT)
        pdf.body_text(exam)

    pdf.section_title("ASSESSMENT (A)")
    pdf.body_text(_safe(note.get("assessment"), "Not documented"))

    pdf.section_title("PLAN (P)")
    pdf.body_text(_safe(note.get("plan"), "Not documented"))

    # ── ICD-10 ────────────────────────────────────────────────────────────────
    pdf.section_title("ICD-10 CODES")
    pdf.body_text(icd_text)

    # ── Additional fields ─────────────────────────────────────────────────────
    meds = _safe(note.get("medications"), "")
    allergies = _safe(note.get("allergies"), "")
    follow_up = _safe(note.get("follow_up"), "")

    if any(v and v != "—" for v in [meds, allergies, follow_up]):
        pdf.section_title("ADDITIONAL INFORMATION")
        if meds and meds != "—":
            pdf.kv_row("Medications", meds)
        if allergies and allergies != "—":
            pdf.kv_row("Allergies", allergies)
        if follow_up and follow_up != "—":
            pdf.kv_row("Follow-up", follow_up)
        pdf.ln(2)

    # ── Finalization stamp ────────────────────────────────────────────────────
    if is_finalized and finalized_at:
        pdf.ln(4)
        pdf.set_fill_color(236, 253, 245)
        pdf.set_draw_color(*PRIMARY)
        pdf.set_line_width(0.4)
        pdf.rect(18, pdf.get_y(), 174, 10, "FD")
        pdf.set_xy(22, pdf.get_y() + 2)
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_text_color(*PRIMARY)
        pdf.cell(0, 6, f"[Finalized]  Signed by Dr. {doctor_name}  -  {finalized_at}", ln=1)
        pdf.set_text_color(*DARK_TEXT)

    return bytes(pdf.output())
