"""
instructions_generator.py — Patient take-home instructions PDF via fpdf2.
Reuses extract_medications() from prescription_generator to avoid a duplicate LLM call.
"""

import logging
import re
from datetime import datetime, timezone, timedelta

from fpdf import FPDF
from openai import AsyncOpenAI

from app.config import settings
from app.services.prescription_generator import (
    PrescriptionExtraction,
    _ascii,
    _safe,
    _format_ist,
    extract_medications,
    PRIMARY,
    LIGHT_BG,
    DARK_TEXT,
    MUTED,
    BORDER,
    IST,
)

logger = logging.getLogger(__name__)


async def _simplify_assessment(assessment: str) -> str:
    if not assessment:
        return ""
    try:
        client = AsyncOpenAI(
            api_key=settings.perplexity_api_key,
            base_url=settings.perplexity_base_url,
        )
        resp = await client.chat.completions.create(
            model=settings.perplexity_model,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a patient-facing medical assistant. Explain the diagnosis "
                        "in simple language a non-medical person can understand. "
                        "Max 2 sentences. No jargon."
                    ),
                },
                {"role": "user", "content": f"Clinical assessment: {assessment}"},
            ],
            timeout=20,
        )
        raw = resp.choices[0].message.content or ""
        raw = re.sub(r"<think>.*?</think>\s*", "", raw, flags=re.DOTALL).strip()
        return raw
    except Exception as exc:
        logger.warning("_simplify_assessment failed: %s", exc)
        return assessment


# ── PDF renderer ──────────────────────────────────────────────────────────────

class _InstructionsPDF(FPDF):
    def __init__(self, date_str: str):
        super().__init__()
        self._date = date_str

    def header(self):
        self.set_fill_color(*PRIMARY)
        self.rect(0, 0, 210, 16, "F")
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(255, 255, 255)
        self.set_xy(10, 4)
        self.cell(90, 8, "Chartr", ln=False)
        self.set_font("Helvetica", "", 9)
        self.set_x(110)
        self.cell(90, 8, f"Your Visit Summary  |  {self._date}", align="R", ln=True)
        self.set_text_color(*DARK_TEXT)
        self.ln(2)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*MUTED)
        self.cell(0, 6, "Generated by Chartr  |  Keep this sheet for your records", align="C")

    def section_header(self, title: str):
        self.set_fill_color(*PRIMARY)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 9)
        self.cell(0, 7, f"  {title}", fill=True, ln=True)
        self.set_text_color(*DARK_TEXT)
        self.ln(1)


def _render_instructions_pdf(
    extraction: PrescriptionExtraction,
    plain_assessment: str,
    warning_signs: list[str],
    doctor_name: str,
    patient_name: str,
    date_str: str,
) -> bytes:
    pdf = _InstructionsPDF(date_str)
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Patient / doctor info bar
    pdf.set_fill_color(*LIGHT_BG)
    pdf.rect(10, pdf.get_y(), 190, 14, "F")
    pdf.set_xy(14, pdf.get_y() + 3)
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(90, 5, f"Patient: {_safe(patient_name)}", ln=False)
    pdf.cell(90, 5, f"Doctor: {_safe(doctor_name)}", align="R", ln=True)
    pdf.ln(6)

    # What was found
    if plain_assessment:
        pdf.section_header("WHAT WAS FOUND TODAY")
        pdf.set_font("Helvetica", "", 9)
        pdf.multi_cell(0, 6, _ascii(plain_assessment))
        pdf.ln(3)

    # Medications
    pdf.section_header("YOUR MEDICATIONS")
    if extraction.medications:
        pdf.set_font("Helvetica", "", 9)
        for i, med in enumerate(extraction.medications, 1):
            line = f"  {i}.  {_safe(med.drug_name)} {_safe(med.dose)}  —  {_safe(med.frequency)}"
            if med.duration and med.duration.lower() not in ("ongoing", "as needed", "-"):
                line += f", {_safe(med.duration)}"
            pdf.cell(0, 6, line, ln=True)
            if med.instructions:
                pdf.set_font("Helvetica", "I", 8)
                pdf.set_text_color(*MUTED)
                pdf.cell(0, 5, f"      {_safe(med.instructions)}", ln=True)
                pdf.set_text_color(*DARK_TEXT)
                pdf.set_font("Helvetica", "", 9)
        pdf.ln(2)
    else:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 6, "  No medications prescribed.", ln=True)
        pdf.set_text_color(*DARK_TEXT)
    pdf.ln(2)

    # Tests
    if extraction.investigations:
        pdf.section_header("TESTS TO GET DONE")
        pdf.set_font("Helvetica", "", 9)
        for inv in extraction.investigations:
            pdf.cell(0, 5, f"  - {_safe(inv)}", ln=True)
        pdf.ln(3)

    # Warning signs
    if warning_signs:
        pdf.set_fill_color(254, 243, 199)   # amber light
        pdf.set_text_color(146, 64, 14)     # amber dark
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(0, 7, "  COME BACK IMMEDIATELY IF:", fill=True, ln=True)
        pdf.set_text_color(*DARK_TEXT)
        pdf.set_font("Helvetica", "", 9)
        pdf.ln(1)
        for sign in warning_signs:
            pdf.cell(0, 5, f"  - {_ascii(sign)}", ln=True)
        pdf.ln(3)

    # Follow-up + special instructions
    if extraction.follow_up or extraction.special_instructions:
        pdf.set_draw_color(*BORDER)
        pdf.set_line_width(0.3)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(3)
        pdf.set_font("Helvetica", "", 9)
        if extraction.follow_up:
            pdf.cell(0, 5, f"Next visit: {_safe(extraction.follow_up)}", ln=True)
        if extraction.special_instructions:
            pdf.cell(0, 5, _safe(extraction.special_instructions), ln=True)

    return bytes(pdf.output())


# ── Public API ────────────────────────────────────────────────────────────────

async def generate_instructions_pdf(
    note: dict,
    session: dict,
    doctor_name: str,
    patient_name: str = "Unknown",
    patient_age: int | None = None,
) -> bytes:
    extraction, plain_assessment = await _run_parallel(note)
    # warning_signs come from the LLM extraction — more reliable than keyword matching
    warning_signs = extraction.warning_signs
    started_at = session.get("started_at")
    date_str = _format_ist(started_at)
    try:
        return _render_instructions_pdf(
            extraction, plain_assessment, warning_signs, doctor_name, patient_name, date_str
        )
    except Exception as exc:
        logger.error("Instructions PDF render failed: %s", exc)
        fallback = PrescriptionExtraction()
        return _render_instructions_pdf(
            fallback, note.get("assessment") or "", [], doctor_name, patient_name, date_str
        )


async def _run_parallel(note: dict):
    import asyncio
    return await asyncio.gather(
        extract_medications(note),
        _simplify_assessment(note.get("assessment") or ""),
    )
