"""
prescription_generator.py — Prescription PDF via fpdf2.
extract_medications() is the shared extraction function reused by instructions_generator.py.
"""

import json
import logging
import re
from datetime import datetime, timezone, timedelta

from fpdf import FPDF
from openai import AsyncOpenAI
from pydantic import BaseModel

from app.config import settings

logger = logging.getLogger(__name__)

IST = timedelta(hours=5, minutes=30)
PRIMARY = (1, 105, 111)
LIGHT_BG = (245, 248, 248)
DARK_TEXT = (31, 41, 55)
MUTED = (107, 114, 128)
BORDER = (209, 213, 219)

_UNICODE_REPLACEMENTS = str.maketrans({
    "—": "-", "–": "-", "•": "-",
    "'": "'", "'": "'", "“": '"', "”": '"',
    "…": "...", "·": ".", "→": "->",
})


def _ascii(text: str) -> str:
    return text.translate(_UNICODE_REPLACEMENTS).encode("latin-1", errors="replace").decode("latin-1")


def _safe(value, fallback="-") -> str:
    if value is None or str(value).strip() == "":
        return fallback
    return _ascii(str(value).strip())


def _format_ist(dt: datetime | None) -> str:
    if not dt:
        return datetime.now(timezone(IST)).strftime("%d %b %Y")
    try:
        return dt.astimezone(timezone(IST)).strftime("%d %b %Y")
    except Exception:
        return str(dt)


# ── Pydantic schemas ──────────────────────────────────────────────────────────

class MedicationItem(BaseModel):
    drug_name: str
    dose: str
    frequency: str
    duration: str
    instructions: str = ""


class PrescriptionExtraction(BaseModel):
    medications: list[MedicationItem] = []
    special_instructions: str = ""
    investigations: list[str] = []
    follow_up: str = ""
    warning_signs: list[str] = []  # Sprint 9: populated from plan, used by instructions sheet


# ── Shared extraction (reused by instructions_generator.py) ──────────────────

async def extract_medications(note: dict) -> PrescriptionExtraction:
    """
    Parse note["medications"] + note["plan"] into structured PrescriptionExtraction.
    Called by both generate_prescription_pdf() and generate_instructions_pdf()
    so only ONE LLM call is made per session when both documents are downloaded.
    """
    plan = note.get("plan") or ""
    meds = note.get("medications") or ""

    if not plan and not meds:
        return PrescriptionExtraction()

    try:
        client = AsyncOpenAI(
            api_key=settings.perplexity_api_key,
            base_url=settings.perplexity_base_url,
        )
        resp = await client.chat.completions.create(
            model=settings.perplexity_model,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a medical scribe. Extract structured prescription data "
                        "from the clinical note text. Return valid JSON only matching this schema:\n"
                        '{"medications":[{"drug_name":"","dose":"","frequency":"","duration":"","instructions":""}],'
                        '"special_instructions":"","investigations":[],"follow_up":"","warning_signs":[]}'
                        "\n\nwarning_signs: plain English phrases for when patient should seek immediate care."
                    ),
                },
                {
                    "role": "user",
                    "content": f"Plan section:\n{plan}\n\nMedications field:\n{meds}",
                },
            ],
            timeout=30,
        )
        raw = resp.choices[0].message.content or ""
        # Strip <think>…</think> reasoning tokens (r1-1776)
        raw = re.sub(r"<think>.*?</think>\s*", "", raw, flags=re.DOTALL)
        # Strip markdown fences if present
        if "```" in raw:
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]
        return PrescriptionExtraction(**json.loads(raw.strip()))
    except Exception as exc:
        logger.warning("extract_medications failed: %s", exc)
        return PrescriptionExtraction()


# ── PDF renderer ──────────────────────────────────────────────────────────────

class _PrescriptionPDF(FPDF):
    def __init__(self, doctor_name: str, patient_label: str, date_str: str):
        super().__init__()
        self._doctor = _ascii(doctor_name)
        self._patient = _ascii(patient_label)
        self._date = date_str

    def header(self):
        self.set_fill_color(*PRIMARY)
        self.rect(0, 0, 210, 16, "F")
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(255, 255, 255)
        self.set_xy(10, 4)
        self.cell(90, 8, "Chartr", ln=False)
        self.set_font("Helvetica", "", 9)
        self.set_x(110)
        self.cell(90, 8, f"Prescription  |  {self._date}", align="R", ln=True)
        self.set_text_color(*DARK_TEXT)
        self.ln(2)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*MUTED)
        self.cell(0, 6, "Generated by Chartr  |  Confidential  |  For authorized use only", align="C")


def _render_prescription_pdf(
    extraction: PrescriptionExtraction,
    doctor_name: str,
    patient_name: str,
    patient_age: int | None,
    patient_gender: str | None,
    date_str: str,
) -> bytes:
    age_str = f", {patient_age}y" if patient_age else ""
    gender_str = f" ({patient_gender})" if patient_gender else ""
    patient_label = f"{_safe(patient_name)}{age_str}{gender_str}"

    pdf = _PrescriptionPDF(doctor_name, patient_label, date_str)
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Doctor / patient info bar
    pdf.set_fill_color(*LIGHT_BG)
    pdf.rect(10, pdf.get_y(), 190, 16, "F")
    pdf.set_xy(14, pdf.get_y() + 3)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(*DARK_TEXT)
    pdf.cell(90, 5, _ascii(doctor_name), ln=False)
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(90, 5, f"Patient: {patient_label}", align="R", ln=True)
    pdf.ln(8)

    # Rx header
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(*PRIMARY)
    pdf.cell(0, 8, "Rx", ln=True)
    pdf.set_text_color(*DARK_TEXT)
    pdf.ln(2)

    if extraction.medications:
        for i, med in enumerate(extraction.medications, 1):
            pdf.set_font("Helvetica", "B", 9)
            line = f"  {i}.  {_safe(med.drug_name)} {_safe(med.dose)}"
            pdf.cell(100, 6, line, ln=False)
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(45, 6, _safe(med.frequency), ln=False)
            pdf.cell(0, 6, _safe(med.duration), ln=True)
            if med.instructions:
                pdf.set_font("Helvetica", "I", 8)
                pdf.set_text_color(*MUTED)
                pdf.cell(0, 5, f"      {_safe(med.instructions)}", ln=True)
                pdf.set_text_color(*DARK_TEXT)
            pdf.ln(1)
    else:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*MUTED)
        pdf.cell(0, 6, "  No medications documented.", ln=True)
        pdf.set_text_color(*DARK_TEXT)

    pdf.ln(4)

    # Investigations
    if extraction.investigations:
        pdf.set_fill_color(*PRIMARY)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 9)
        pdf.cell(0, 7, "  INVESTIGATIONS ADVISED", fill=True, ln=True)
        pdf.set_text_color(*DARK_TEXT)
        pdf.ln(1)
        pdf.set_font("Helvetica", "", 9)
        for inv in extraction.investigations:
            pdf.cell(0, 5, f"  - {_safe(inv)}", ln=True)
        pdf.ln(3)

    # Special instructions + follow-up
    if extraction.special_instructions or extraction.follow_up:
        pdf.set_draw_color(*BORDER)
        pdf.set_line_width(0.3)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(3)
        pdf.set_font("Helvetica", "", 9)
        if extraction.special_instructions:
            pdf.cell(0, 5, f"Special Instructions: {_safe(extraction.special_instructions)}", ln=True)
        if extraction.follow_up:
            pdf.cell(0, 5, f"Follow-up: {_safe(extraction.follow_up)}", ln=True)
        pdf.ln(4)

    # Signature line
    pdf.set_draw_color(*BORDER)
    pdf.line(10, pdf.get_y(), 90, pdf.get_y())
    pdf.ln(2)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(*MUTED)
    pdf.cell(0, 5, f"Signature: {_ascii(doctor_name)}", ln=True)

    return bytes(pdf.output())


# ── Public API ────────────────────────────────────────────────────────────────

async def generate_prescription_pdf(
    note: dict,
    session: dict,
    doctor_name: str,
    patient_name: str = "Unknown",
    patient_age: int | None = None,
    patient_gender: str | None = None,
) -> bytes:
    extraction = await extract_medications(note)
    started_at = session.get("started_at")
    date_str = _format_ist(started_at)
    try:
        return _render_prescription_pdf(
            extraction, doctor_name, patient_name, patient_age, patient_gender, date_str
        )
    except Exception as exc:
        logger.error("Prescription PDF render failed: %s", exc)
        # Fallback: raw text blob
        fallback = PrescriptionExtraction(
            medications=[],
            special_instructions=note.get("plan") or note.get("medications") or "See clinical note.",
        )
        return _render_prescription_pdf(
            fallback, doctor_name, patient_name, patient_age, patient_gender, date_str
        )
